export interface SpeedMathProblem {
  num1: number;
  num2: number;
  operation: '+' | '-' | '×' | '÷';
  answer: number;
  options: number[];
}

export const generateMathProblem = (level: 'junior' | 'standard' | 'genius'): SpeedMathProblem => {
  let num1: number;
  let num2: number;
  let op: '+' | '-' | '×' | '÷';
  let answer: number;

  if (level === 'junior') {
    const ops: ('+' | '-' | '×')[] = ['+', '-', '×'];
    op = ops[Math.floor(Math.random() * ops.length)];
    if (op === '+') {
      num1 = Math.floor(Math.random() * 20) + 1;
      num2 = Math.floor(Math.random() * 20) + 1;
      answer = num1 + num2;
    } else if (op === '-') {
      num1 = Math.floor(Math.random() * 25) + 10;
      num2 = Math.floor(Math.random() * num1) + 1;
      answer = num1 - num2;
    } else {
      num1 = Math.floor(Math.random() * 10) + 2;
      num2 = Math.floor(Math.random() * 9) + 2;
      answer = num1 * num2;
    }
  } else if (level === 'standard') {
    const ops: ('+' | '-' | '×' | '÷')[] = ['+', '-', '×', '÷'];
    op = ops[Math.floor(Math.random() * ops.length)];
    if (op === '+') {
      num1 = Math.floor(Math.random() * 60) + 20;
      num2 = Math.floor(Math.random() * 60) + 20;
      answer = num1 + num2;
    } else if (op === '-') {
      num1 = Math.floor(Math.random() * 90) + 30;
      num2 = Math.floor(Math.random() * (num1 - 10)) + 10;
      answer = num1 - num2;
    } else if (op === '×') {
      num1 = Math.floor(Math.random() * 14) + 3;
      num2 = Math.floor(Math.random() * 13) + 3;
      answer = num1 * num2;
    } else {
      num2 = Math.floor(Math.random() * 9) + 2;
      answer = Math.floor(Math.random() * 12) + 2;
      num1 = num2 * answer;
    }
  } else {
    // Genius / HOTS
    const ops: ('+' | '-' | '×' | '÷')[] = ['+', '-', '×', '÷'];
    op = ops[Math.floor(Math.random() * ops.length)];
    if (op === '+') {
      num1 = Math.floor(Math.random() * 250) + 120;
      num2 = Math.floor(Math.random() * 250) + 120;
      answer = num1 + num2;
    } else if (op === '-') {
      num1 = Math.floor(Math.random() * 500) + 200;
      num2 = Math.floor(Math.random() * (num1 - 50)) + 50;
      answer = num1 - num2;
    } else if (op === '×') {
      num1 = Math.floor(Math.random() * 25) + 11;
      num2 = Math.floor(Math.random() * 15) + 4;
      answer = num1 * num2;
    } else {
      num2 = Math.floor(Math.random() * 16) + 4;
      answer = Math.floor(Math.random() * 25) + 5;
      num1 = num2 * answer;
    }
  }

  // Generate 3 plausible distractors
  const distractors = new Set<number>();
  while (distractors.size < 3) {
    const delta = (Math.random() > 0.5 ? 1 : -1) * (Math.floor(Math.random() * 5) + 1);
    const candidate = answer + delta;
    if (candidate !== answer && candidate >= 0) {
      distractors.add(candidate);
    }
  }

  const options = Array.from(distractors);
  options.splice(Math.floor(Math.random() * 4), 0, answer);

  return {
    num1,
    num2,
    operation: op,
    answer,
    options
  };
};

